    for name, t in timings.items():
        detail = ", ".join(f"{k} {v:,}" if isinstance(v, int) else f"{k} {v}" for k, v in t.items() if k != "seconds")
        rows.append({"step (golden-datasets equivalent)": name, "seconds": t["seconds"], "output": detail})
    P(md_table(rows, 400) + "\n")
    P("Parsing 1,467 pages (4.0 GB of HTML) and running the 17 rules takes ~4 s; rs-0002 reruns 2 rules on the 1,062 course pages "
      "in ~3 s and copies the rest. The \"rule try\" loop (§3.1 of the spec) is therefore interactive on AVC.\n")

    P("## 3. Files, with real excerpts\n")
    P("### 3.1 `manifest.json` (storage root)\n")
    man = json.loads((ROOT / "golden-dataset-studio/manifest.json").read_text())
    avc = man["catalogs"][0]
    short = {**man, "catalogs": [{**avc, "rule_versions": avc["rule_versions"][:3] + [f"… {len(avc['rule_versions']) - 3} more"]},
                                 man["catalogs"][1], "… 3 more catalogs (Marshall, UALR, WVU), same shape"]}
    P(jblock(short) + "\n")

    P("### 3.2 Rule version: field rule `course-description` v2 (`rules/course-description/v0002.json`)\n")
    P(jblock(json.loads((ROOT / CAT / "golden-dataset-studio/rules/course-description/v0002.json").read_text())) + "\n")
    P("### 3.3 Rule version: record locator `locator-program-requirement` v1 (pulled out of the stub rules' `repeat`)\n")
    P(jblock(json.loads((ROOT / CAT / "golden-dataset-studio/rules/locator-program-requirement/v0001.json").read_text())) + "\n")
    P("For contrast, the imported v1 of `course-description` (`why` empty, prose written for the import):\n")
