    P("### 3.8 `page_labels.parquet` (one row per page × page rule, matched or not)\n")
    P(md_table(q(con, f"SELECT * FROM '{E1}/page_labels.parquet' WHERE page_stem LIKE '%computer-engineering-as%' OR (page_stem LIKE '%geog222%' AND rule_id='course-page')")) + "\n")
    P("### 3.9 `occurrences.parquet`\n")
    P("`occurrence_key` = `<page_stem>@<css_path from the document root>`. The excerpt abbreviates the paths; the full GEOG222 key is:\n")
