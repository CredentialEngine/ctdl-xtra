    P("Signal counts per extraction:\n")
    P(md_table(q(con, f"""SELECT signal, target_kind,
        count(*) FILTER (filename LIKE '%rs-0001%') AS "rs-0001", count(*) FILTER (filename LIKE '%rs-0002%') AS "rs-0002"
        FROM read_parquet('{K}/extractions/*/signals.parquet', filename=true) GROUP BY ALL ORDER BY 3 DESC""")) + "\n")

