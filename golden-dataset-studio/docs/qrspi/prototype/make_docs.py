    P("Paths are found through `golden-dataset-studio/manifest.json`, never by listing (listing Azure costs 23–25 s, research §2.4).\n")

    P("## 2. Steps, row counts and timings\n")
    P("One run of `make_example.py` on Eric's laptop (M-series, 10 worker processes), local folder root:\n")
