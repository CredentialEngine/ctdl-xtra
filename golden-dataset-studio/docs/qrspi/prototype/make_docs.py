    P(jblock({k: v1[k] for k in ("rule_id", "version", "kind", "definition", "what", "how", "why", "content_hash", "depends_on", "imported_from")}) + "\n")
    P("### 3.4 Ruleset version 2 (`rulesets/v0002.json`)\n")
    P(jblock(json.loads((ROOT / CAT / "golden-dataset-studio/rulesets/v0002.json").read_text())) + "\n")

    P("### 3.5 `pages.parquet`\n")
    P(md_table(q(con, f"SELECT * FROM '{K}/pages.parquet' WHERE page_stem LIKE '%geog222%' OR page_stem LIKE '%computer-engineering-as%' OR page_stem LIKE '%allcourses%' ORDER BY page_stem")) + "\n")
    P("### 3.6 `assets/page_assets.parquet` and `assets/assets.parquet`\n")
    P(md_table(q(con, f"SELECT * FROM '{K}/assets/page_assets.parquet' WHERE page_stem LIKE '%geog222%'"), 70) + "\n")
    P(md_table(q(con, f"SELECT url, status, content_type, sha256, bytes, referenced_by FROM '{K}/assets/assets.parquet' LIMIT 5"), 50) + "\n")

    P("### 3.7 `extractions/rs-0002/extraction.json`\n")
